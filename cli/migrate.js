// Open a pull request per GitHub repository with the converted workflow and the conversion notes.
import { client, progress, progressDone } from './http.js';

const MARKER = '<!-- jenkins-to-actions -->';

export async function openPullRequests(recs, { token, api, branch, dryRun }) {
  if (!token) throw new Error('A GitHub token with contents:write and pull_requests:write is required to open PRs.');
  const gh = client({ base: api, auth: { bearer: token }, headers: { 'X-GitHub-Api-Version': '2022-11-28' } });
  const byRepo = new Map();
  for (const r of recs) { if (!r.yaml || !r.repo) continue; if (!byRepo.has(r.repo)) byRepo.set(r.repo, []); byRepo.get(r.repo).push(r); }
  let n = 0;
  for (const [repo, list] of byRepo) {
    n++;
    progress(`[${n}/${byRepo.size}] ${dryRun ? 'would open PR in' : 'opening PR in'} ${repo}`);
    const files = list.map((r) => ({ path: `.github/workflows/${workflowName(r, list.length === 1)}.yml`, content: r.yaml, rec: r }));
    const body = prBody(list, files);
    if (dryRun) { for (const r of list) r.pr = `(dry run) ${files.map((f) => f.path).join(', ')} on ${branch}`; continue; }
    try {
      const repoInfo = await gh.get(`/repos/${repo}`);
      const base = list[0].defaultBranch || repoInfo.default_branch;
      const baseRef = await gh.get(`/repos/${repo}/git/ref/heads/${encodeURIComponent(base)}`);
      const sha = baseRef.object.sha;
      // branch (reuse if it exists)
      let exists = false;
      try { await gh.get(`/repos/${repo}/git/ref/heads/${encodeURIComponent(branch)}`); exists = true; } catch (e) { if (e.status !== 404) throw e; }
      if (!exists) await gh.send('POST', `/repos/${repo}/git/refs`, { ref: `refs/heads/${branch}`, sha });
      // files
      for (const f of files) {
        let existingSha;
        try { const cur = await gh.get(`/repos/${repo}/contents/${f.path}?ref=${encodeURIComponent(branch)}`); existingSha = cur.sha; } catch (e) { if (e.status !== 404) throw e; }
        await gh.send('PUT', `/repos/${repo}/contents/${f.path}`, { message: `ci: add GitHub Actions workflow converted from ${f.rec.path || f.rec.system}`, content: Buffer.from(f.content).toString('base64'), branch, sha: existingSha });
      }
      // PR (reuse open one on the same head)
      const open = await gh.get(`/repos/${repo}/pulls?head=${encodeURIComponent(repo.split('/')[0] + ':' + branch)}&state=open`);
      let pr;
      if (open.length) { pr = await gh.send('PATCH', `/repos/${repo}/pulls/${open[0].number}`, { body }); }
      else pr = await gh.send('POST', `/repos/${repo}/pulls`, { title: `Migrate CI to GitHub Actions (${list.map((r) => r.path || r.system).join(', ')})`, head: branch, base, body, draft: false });
      for (const r of list) r.pr = pr.html_url;
    } catch (e) {
      for (const r of list) { r.pr = null; r.notes.push(`Could not open a pull request: ${e.message}`); }
    }
  }
  progressDone();
  const opened = [...byRepo.values()].flat().filter((r) => r.pr && !String(r.pr).startsWith('(dry')).map((r) => r.pr);
  if (!dryRun) console.log(`${new Set(opened).size} pull request(s) opened.`);
}

function workflowName(r, single = true) {
  if (single) return 'ci';
  const sys = r.system === 'jenkins-config' ? 'jenkins' : r.system;
  return `ci-${sys}`;
}

function prBody(list, files) {
  const L = [MARKER, '## CI migration to GitHub Actions', ''];
  L.push(`This pull request was generated by [jenkins-to-actions](https://github.com/Huckcity/jenkins-to-actions). It converts the existing CI configuration into a GitHub Actions workflow. **Review it before merging**: every construct without a clean equivalent is a \`TODO\` step that fails on purpose, and the notes below list what to check.`, '');
  for (const r of list) {
    const f = files.find((x) => x.rec === r);
    L.push(`### \`${r.path || r.system}\` → \`${f.path}\``, '');
    L.push(`Effort estimate: ${r.hours < 1 ? `${Math.round(r.hours * 60)} min` : `${Math.round(r.hours * 2) / 2} h`}${r.todos ? ` · ${r.todos} TODO step${r.todos > 1 ? 's' : ''}` : ' · no TODO steps'}`, '');
    if (r.secrets.length) L.push(`Secrets to create: ${r.secrets.map((s) => `\`${s}\``).join(', ')}`, '');
    if (r.notes.length) { L.push('Notes:', ''); for (const n of r.notes) L.push(`- ${n}`); L.push(''); }
  }
  L.push('---', '', 'Once the workflow is green, remove the old CI configuration file in a follow-up commit.');
  return L.join('\n');
}
